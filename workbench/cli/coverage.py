"""The static exam-coverage map served by `GET /`.

Each owned statement is one line of this map: its file and the line of the code
that carries it. `scripts/coverage_map.py` writes the file, and pytest runs that
script with `--check`. A moved line changes what the script would write, so the
suite fails instead of `GET /` publishing a reference that no longer matches.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True, slots=True)
class Statement:
    """One owned exam statement and the line of code that anchors it."""

    id: str
    subject: str
    slice_id: str
    path: str
    needle: str


#: The four statements this repo owns. 1.6, 2.3 and 5.1 are exercised in 20.4 and
#: owned by app 18, so they are not rows of this map.
STATEMENTS: tuple[Statement, ...] = (
    Statement(
        "1.2",
        "Coordinator and subagents",
        "20.4",
        "workbench/coordinator/coordinator.py",
        "class DiscoveryCoordinator:",
    ),
    Statement(
        "1.3",
        "Subagent invocation and context passing",
        "20.4",
        "workbench/coordinator/agents.py",
        "class SpecialistAgent(AgentLoop):",
    ),
    Statement(
        "5.3",
        "Error propagation across agents",
        "20.4",
        "workbench/coordinator/coordinator.py",
        "def _record_failure(",
    ),
    Statement(
        "5.6",
        "Provenance and uncertainty in synthesis",
        "20.5",
        "workbench/readout/template.py",
        'level: int | str = item.level if claim_ids else "unknown"',
    ),
)

_HEADER = """\
# Static exam-coverage map. Generated by scripts/coverage_map.py.
# Do not edit. pytest runs that script, so a moved line fails the suite
# instead of GET / publishing a stale file and line.
"""


def map_path() -> Path:
    """The committed map, next to this module so the wheel carries it."""
    return Path(__file__).resolve().parent / "exam_coverage.txt"


def render(root: Path) -> str:
    """The map text for `root`. Raises if an anchor is missing or ambiguous."""
    rows = [_HEADER.rstrip("\n")]
    for item in STATEMENTS:
        line_no = _line_number(root / item.path, item.needle, item.id)
        rows.append(f"{item.id}\t{item.subject}\t{item.slice_id}\t{item.path}:{line_no}")
    return "\n".join(rows) + "\n"


def _line_number(path: Path, needle: str, statement_id: str) -> int:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise RuntimeError(f"statement {statement_id} anchor could not be read") from exc
    hits = [number for number, line in enumerate(lines, start=1) if needle in line]
    if len(hits) != 1:
        raise RuntimeError(
            f"statement {statement_id} must match exactly one line, found {len(hits)}"
        )
    return hits[0]
